/**
 * Calculates real Bihar DISCOM solar sizing, roof area, annual savings, and PM Surya Ghar subsidy
 * @param {number} bill - Monthly electricity bill in INR
 * @param {string} selectedType - Application type ('Home Solar' | 'Commercial Solar' | 'Solar Pump' | 'Mill Solar')
 */
export function calculateSolarMetrics(bill, selectedType = "Home Solar") {
  const monthlyUnits = bill / 7.5;
  let kwNum = parseFloat((monthlyUnits / 120).toFixed(1));
  if (kwNum < 1.0) kwNum = 1.0;

  const kwDisplay = kwNum.toFixed(1);
  const area = Math.round(kwNum * 100);
  const annualSavings = Math.round(bill * 12 * 0.9);

  let subsidyText = "₹0";
  let payback = "3.2 Yrs";

  if (selectedType === "Home Solar") {
    if (kwNum <= 1.2) {
      subsidyText = "₹30,000";
      payback = "2.9 Yrs";
    } else if (kwNum <= 2.2) {
      subsidyText = "₹60,000";
      payback = "3.1 Yrs";
    } else {
      subsidyText = "₹78,000";
      payback = "3.2 Yrs";
    }
  } else if (selectedType === "Commercial Solar") {
    subsidyText = "Tax Deprec.*";
    payback = "2.8 Yrs";
  } else if (selectedType === "Solar Pump") {
    subsidyText = "KUSUM Eligible*";
    payback = "2.5 Yrs";
  } else {
    subsidyText = "Commercial ROI";
    payback = "2.2 Yrs";
  }

  const waMessage = `Hello Smart Solar Solutions, I calculated on your website for a monthly bill of ₹${bill.toLocaleString(
    "en-IN"
  )} (${selectedType}). Recommended System: ${kwDisplay} kW (${area} sq.ft roof). Please share a quotation.`;
  const whatsappUrl = `https://wa.me/919931798080?text=${encodeURIComponent(
    waMessage
  )}`;

  return {
    kwDisplay,
    area,
    annualSavings,
    subsidyText,
    payback,
    whatsappUrl,
    calcWaHref: whatsappUrl,
  };
}

